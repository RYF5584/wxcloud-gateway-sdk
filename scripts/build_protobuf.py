#!/usr/bin/env python3
"""Generate protobuf Python code from the .proto file.

The generated pb2 ships with the package, so its gencode version must not be
newer than the minimum protobuf runtime declared in pyproject.toml
(currently >=4.25.1); otherwise older runtimes refuse to load it
(protobuf allows "newer runtime + older gencode" but not the reverse).

Therefore this script pins grpcio-tools 1.62.x (bundling protoc 25.1,
gencode 4.25.1). On Python >= 3.13 grpcio-tools 1.62.x has no prebuilt
wheel; run this script from a Python <= 3.12 virtualenv instead, e.g.:

    uv venv /tmp/protoc-venv --python 3.12
    uv pip install --python /tmp/protoc-venv/bin/python "grpcio-tools==1.62.3"
    /tmp/protoc-venv/bin/python scripts/build_protobuf.py

Usage:
    python scripts/build_protobuf.py

Author: RYF5584
    WeChat: RSComapnyCEO
    QQ: 1043695584
    Telegram: ryf5584
    GitHub: https://github.com/RYF5584
"""
import re
import subprocess
import sys
from pathlib import Path

#: Minimum protobuf runtime declared in pyproject.toml
MIN_PROTOBUF_RUNTIME = (4, 25, 1)

#: grpcio-tools version used to generate the pb2
#: (bundles protoc 25.1, gencode 4.25.1)
GRPCIO_TOOLS_PIN = "grpcio-tools==1.62.3"

#: Author header injected into the generated pb2 file
PB2_AUTHOR_HEADER = """
# WeChat Cloud Gateway SDK - generated protobuf module.
# Regenerate with: python scripts/build_protobuf.py
#
# Author: RYF5584
#     WeChat: RSComapnyCEO
#     QQ: 1043695584
#     Telegram: ryf5584
#     GitHub: https://github.com/RYF5584
"""


def _parse_gencode_version(generated: Path) -> tuple:
    """Parse the gencode version from the generated pb2 file header,
    e.g. (4, 25, 1)."""
    match = re.search(
        r"Protobuf Python Version: (\d+)\.(\d+)\.(\d+)",
        generated.read_text(encoding="utf-8"),
    )
    if not match:
        # Files generated by protoc <= 25.x carry no runtime version check
        # and are compatible with any runtime
        return MIN_PROTOBUF_RUNTIME
    return tuple(int(part) for part in match.groups())


def _inject_author_header(generated: Path) -> None:
    """Insert the author header after the protoc version line."""
    content = generated.read_text(encoding="utf-8")
    marker = "# Protobuf Python Version:"
    lines = content.split("\n")
    for i, line in enumerate(lines):
        if line.startswith(marker):
            lines.insert(i + 1, PB2_AUTHOR_HEADER)
            break
    else:
        # No version line found; prepend the header after the coding line
        lines.insert(1, PB2_AUTHOR_HEADER)
    generated.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    proto_dir = root / "proto"
    out_dir = root / "src" / "wxcloud_gateway_sdk"

    proto_file = proto_dir / "wxcloud.proto"
    if not proto_file.exists():
        print(f"Error: {proto_file} not found", file=sys.stderr)
        sys.exit(1)

    # Use the grpcio_tools protoc (version pinned for gencode compatibility)
    try:
        import grpc_tools  # noqa: F401
    except ImportError:
        print(f"Installing {GRPCIO_TOOLS_PIN}...", file=sys.stderr)
        subprocess.check_call(
            [sys.executable, "-m", "pip", "install", GRPCIO_TOOLS_PIN]
        )

    import grpc_tools

    grpc_tools_dir = Path(grpc_tools.__file__).parent
    include_dir = grpc_tools_dir / "_proto"

    cmd = [
        sys.executable,
        "-m",
        "grpc_tools.protoc",
        f"--proto_path={proto_dir}",
        f"--proto_path={include_dir}",
        f"--python_out={out_dir}",
        str(proto_file),
    ]
    print(f"Running: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"protoc failed: {result.stderr}", file=sys.stderr)
        sys.exit(1)

    generated = out_dir / "wxcloud_pb2.py"
    if not generated.exists():
        print(f"Error: {generated} was not created", file=sys.stderr)
        sys.exit(1)

    # Guard: the gencode version must not exceed the declared minimum
    # runtime, otherwise older runtimes cannot load the module
    gencode = _parse_gencode_version(generated)
    if gencode > MIN_PROTOBUF_RUNTIME:
        generated.unlink()
        print(
            "Error: generated gencode version {}.{}.{} is newer than the "
            "declared minimum runtime protobuf >= {}.{}.{}. Regenerate with "
            "{} (see script docstring for details).".format(
                *gencode, *MIN_PROTOBUF_RUNTIME, GRPCIO_TOOLS_PIN
            ),
            file=sys.stderr,
        )
        sys.exit(1)

    _inject_author_header(generated)

    print("Generated: {} (gencode {}.{}.{})".format(generated, *gencode))


if __name__ == "__main__":
    main()
